"""Regenerate proofengine/_schema.py from the Go-generated schema.

    python3 -I sync_schema.py

The statement schema is defined once, in engine/posture/schema.go. Go writes
it to testdata/vectors/posture-schema.json; this script embeds that file as
a Python module so the validator never reads files at run time. The unit
tests fail if the two drift apart.
"""

import json
import pathlib
import pprint

here = pathlib.Path(__file__).resolve().parent
src = here.parent / "testdata" / "vectors" / "posture-schema.json"
schema = json.loads(src.read_text(encoding="utf-8"))
out = here / "proofengine" / "_schema.py"
out.write_text(
    '"""Generated by sync_schema.py from testdata/vectors/posture-schema.json. Do not edit."""\n\n'
    "SCHEMA = " + pprint.pformat(schema, indent=1, width=110, sort_dicts=True) + "\n",
    encoding="utf-8",
)
print(f"wrote {out}")
